# ============================================================================
# BUILD LSTM MODEL
# ============================================================================

print("\n" + "="*70)
print("STEP 4: BUILD LSTM MODEL")
print("="*70)

num_classes = 6
input_shape = (X_train.shape[1], X_train.shape[2])  # (128, 6)

model = keras.Sequential([
    # First LSTM layer
    layers.LSTM(128, return_sequences=True, input_shape=input_shape),
    layers.Dropout(0.3),

    # Second LSTM layer
    layers.LSTM(64),
    layers.Dropout(0.3),

    # Dense layers
    layers.Dense(32, activation='relu'),
    layers.Dropout(0.2),

    # Output layer
    layers.Dense(num_classes, activation='softmax')
])

model.compile(
    optimizer='adam',
    loss='sparse_categorical_crossentropy',
    metrics=['accuracy']
)

print("✓ Model built successfully!")
print(f"\nModel Architecture:")
model.summary()

# ============================================================================
# TRAIN MODEL
# ============================================================================

print("\n" + "="*70)
print("STEP 5: TRAIN MODEL")
print("="*70)

EPOCHS = 50  # Increase epochs
BATCH_SIZE = 32  # Smaller batch for better learning

# Add class weights to handle imbalance
from sklearn.utils import class_weight
class_weights = class_weight.compute_class_weight(
    'balanced',
    classes=np.unique(y_train),
    y=y_train
)
class_weight_dict = dict(enumerate(class_weights))

print(f"\nTraining configuration:")
print(f"  Epochs: {EPOCHS}")
print(f"  Batch size: {BATCH_SIZE}")
print(f"  Training samples: {len(X_train):,}")
print(f"  Validation samples: {len(X_test):,}")
print(f"  Class weights: {class_weight_dict}")

print(f"\n🚀 Starting training...\n")

history = model.fit(
    X_train, y_train,
    epochs=EPOCHS,
    batch_size=BATCH_SIZE,
    validation_data=(X_test, y_test),
    class_weight=class_weight_dict,  # ADD THIS!
    verbose=1
)

print("\n✓ Training completed!")

# ============================================================================
# EVALUATE MODEL
# ============================================================================

print("\n" + "="*70)
print("STEP 6: EVALUATE MODEL")
print("="*70)

# Evaluate on test set
test_loss, test_accuracy = model.evaluate(X_test, y_test, verbose=0)
print(f"\n{'='*50}")
print(f"TEST SET RESULTS:")
print(f"{'='*50}")
print(f"  Loss: {test_loss:.4f}")
print(f"  Accuracy: {test_accuracy*100:.2f}%")
print(f"{'='*50}")

# Make predictions
y_pred = model.predict(X_test, verbose=0)
y_pred_classes = np.argmax(y_pred, axis=1)

# Classification report
print(f"\n📋 Detailed Classification Report:")
print(f"{'='*70}")
print(classification_report(y_test, y_pred_classes,
                          target_names=activity_labels.values(),
                          digits=3))

# Per-class accuracy
print(f"\n📊 Per-Class Accuracy:")
print(f"{'='*50}")
for i, activity in activity_labels.items():
    mask = y_test == (i-1)
    if mask.sum() > 0:
        class_acc = accuracy_score(y_test[mask], y_pred_classes[mask])
        print(f"  {activity:20s}: {class_acc*100:5.2f}%")

