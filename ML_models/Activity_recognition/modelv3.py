def load_uci_har_data():
    """
    Load UCI HAR dataset from Inertial Signals folder
    Returns data with shape (samples, 128, 6) for 6 sensor channels
    """

    # Activity labels
    activity_labels = {
        1: 'Walking',
        2: 'Walking_Upstairs',
        3: 'Walking_Downstairs',
        4: 'Sitting',
        5: 'Standing',
        6: 'Laying'
    }

    print("Loading training data...")

    # Load training data (Inertial Signals)
    train_path = 'UCI HAR Dataset/train/Inertial Signals/'

    # Accelerometer data
    train_acc_x = np.loadtxt(train_path + 'body_acc_x_train.txt')
    train_acc_y = np.loadtxt(train_path + 'body_acc_y_train.txt')
    train_acc_z = np.loadtxt(train_path + 'body_acc_z_train.txt')

    # Gyroscope data
    train_gyro_x = np.loadtxt(train_path + 'body_gyro_x_train.txt')
    train_gyro_y = np.loadtxt(train_path + 'body_gyro_y_train.txt')
    train_gyro_z = np.loadtxt(train_path + 'body_gyro_z_train.txt')

    # Stack along last axis to get shape (samples, 128, 6)
    X_train = np.stack([train_acc_x, train_acc_y, train_acc_z,
                        train_gyro_x, train_gyro_y, train_gyro_z], axis=2)

    # Load training labels
    y_train = np.loadtxt('UCI HAR Dataset/train/y_train.txt')
    y_train = y_train - 1  # Convert to 0-based indexing

    print("Loading test data...")

    # Load test data (Inertial Signals)
    test_path = 'UCI HAR Dataset/test/Inertial Signals/'

    # Accelerometer data
    test_acc_x = np.loadtxt(test_path + 'body_acc_x_test.txt')
    test_acc_y = np.loadtxt(test_path + 'body_acc_y_test.txt')
    test_acc_z = np.loadtxt(test_path + 'body_acc_z_test.txt')

    # Gyroscope data
    test_gyro_x = np.loadtxt(test_path + 'body_gyro_x_test.txt')
    test_gyro_y = np.loadtxt(test_path + 'body_gyro_y_test.txt')
    test_gyro_z = np.loadtxt(test_path + 'body_gyro_z_test.txt')

    # Stack along last axis
    X_test = np.stack([test_acc_x, test_acc_y, test_acc_z,
                       test_gyro_x, test_gyro_y, test_gyro_z], axis=2)

    # Load test labels
    y_test = np.loadtxt('UCI HAR Dataset/test/y_test.txt')
    y_test = y_test - 1  # Convert to 0-based indexing

    print(f"\n✓ Dataset loaded successfully!")
    print(f"\nTraining data:")
    print(f"  X_train shape: {X_train.shape} (samples, timesteps, channels)")
    print(f"  y_train shape: {y_train.shape}")
    print(f"\nTest data:")
    print(f"  X_test shape: {X_test.shape}")
    print(f"  y_test shape: {y_test.shape}")

    # Show activity distribution
    print(f"\n📊 Activity Distribution:")
    print(f"{'='*50}")
    for i, activity in activity_labels.items():
        train_count = np.sum(y_train == i-1)
        test_count = np.sum(y_test == i-1)
        print(f"  {activity:20s}: Train={train_count:4d}, Test={test_count:4d}")

    return X_train, y_train.astype(int), X_test, y_test.astype(int), activity_labels

# Load data
X_train, y_train, X_test, y_test, activity_labels = load_uci_har_data()

